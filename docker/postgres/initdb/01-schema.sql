CREATE TABLE IF NOT EXISTS spy (
    date   TIMESTAMP PRIMARY KEY,
    open   NUMERIC(12, 4) NOT NULL,
    high   NUMERIC(12, 4) NOT NULL,
    low    NUMERIC(12, 4) NOT NULL,
    close  NUMERIC(12, 4) NOT NULL,
    volume BIGINT,
    symbol TEXT
);

CREATE TABLE IF NOT EXISTS qqq (LIKE spy INCLUDING ALL);
CREATE TABLE IF NOT EXISTS dia (LIKE spy INCLUDING ALL);
CREATE TABLE IF NOT EXISTS iwm (LIKE spy INCLUDING ALL);
